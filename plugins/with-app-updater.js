// The in-app updater hands the APKs published on GitHub Releases to Android's
// package installer, which needs REQUEST_INSTALL_PACKAGES.
//
// Google Play forbids apps that update themselves and restricts that
// permission. The Play bundle is therefore built with
// `./gradlew app:bundleRelease -PplantulePlayBuild=true`, which removes the
// permission, and without EXPO_PUBLIC_UPDATE_CHANNEL, so its JS never looks
// for updates (src/updates/channel.ts). Both can be built from the same
// android/ folder: the JS bundle is rebuilt whenever that variable changes.
const { AndroidConfig, withAndroidManifest, withAppBuildGradle, withDangerousMod } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const PERMISSION = 'android.permission.REQUEST_INSTALL_PACKAGES';
const PLAY_MANIFEST = 'src/play/AndroidManifest.xml';
const MARKER = '// with-app-updater';

const playManifest = `<!-- Generated by plugins/with-app-updater.js: the Google Play build does not update itself. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android" xmlns:tools="http://schemas.android.com/tools">
    <uses-permission android:name="${PERMISSION}" tools:node="remove" />
</manifest>
`;

const gradleBlock = `
${MARKER}: the Google Play build (-PplantulePlayBuild=true) may not update itself.
if (findProperty('plantulePlayBuild') == 'true') {
    android.sourceSets.release.manifest.srcFile '${PLAY_MANIFEST}'
}
// The update channel is inlined in the JS bundle: bundle again when it changes.
tasks.matching { it.name.startsWith('createBundle') }.configureEach {
    inputs.property('plantuleUpdateChannel', providers.environmentVariable('EXPO_PUBLIC_UPDATE_CHANNEL').orElse(''))
}
`;

function addGradleBlock(buildGradle) {
  if (buildGradle.includes(MARKER)) {
    return buildGradle;
  }
  return `${buildGradle.trimEnd()}\n${gradleBlock}`;
}

module.exports = function withAppUpdater(config) {
  config = withAndroidManifest(config, (config) => {
    AndroidConfig.Permissions.ensurePermission(config.modResults, PERMISSION);
    return config;
  });

  config = withDangerousMod(config, [
    'android',
    (config) => {
      const file = path.join(config.modRequest.platformProjectRoot, 'app', PLAY_MANIFEST);
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, playManifest);
      return config;
    },
  ]);

  return withAppBuildGradle(config, (config) => {
    if (config.modResults.language !== 'groovy') {
      throw new Error('with-app-updater: expected a Groovy android/app/build.gradle');
    }
    config.modResults.contents = addGradleBlock(config.modResults.contents);
    return config;
  });
};
